#!/usr/bin/env node
// Генерирует список WARP-прокси внутри config/templates/clash.yaml, между
// маркерами "# === BEGIN/END WARP PROXIES ===". Всё вне маркеров (anchors, dns,
// rule-providers, proxy-groups, rules) не трогает. Идемпотентно — можно
// перезапускать. Пул настраивается через RANGES / PORTS ниже.
//
//   node scripts/gen-endpoints.mjs      (или: npm run gen:endpoints)

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const BEGIN = "# === BEGIN WARP PROXIES (vendored, generated by scripts/gen-endpoints.mjs) ===";
const END = "# === END WARP PROXIES ===";

// По одному IP на известный рабочий диапазон Cloudflare WARP. Лишние IP в том же
// /24 бесполезны (тот же anycast-префикс) — поэтому варьируем ПОРТЫ, а не IP:
// именно разнообразие портов обходит DPI в РФ. Замените, если диапазон отвалился.
const RANGES = [
  "162.159.192.1", "162.159.195.1", "8.6.112.1", "8.34.70.1", "8.34.146.1",
  "8.35.211.1", "8.39.125.1", "8.39.204.1", "8.39.214.1", "8.47.69.1",
  "188.114.96.1", "188.114.97.1", "188.114.98.1",
];

// 4 стандартных WARP-порта + экзотический 2371 (анти-DPI). Каждый порт
// комбинируется с каждым диапазоном → пул ☁️-эндпоинтов (RANGES × PORTS).
const PORTS = [500, 2408, 4500, 2371];

// ─────────────────────────── YAML-хелперы ─────────────────────────────────
const comment = (text) => `  # ── ${text} ──`;

/**
 * Один WARP-прокси. obf (необязательно) добавляет amnezia-обфускацию и метку
 * «(Alt N)» в имя — для origin-эндпоинтов с альтернативными i1-масками.
 */
function endpoint(prefix, server, port, obf) {
  const tag = obf ? `(${obf.label}) ` : "";
  const lines = [
    `  - name: "[${prefix}] ${tag}${server}:${port}"`,
    `    <<: *warp-common`,
    `    server: ${server}`,
    `    port: ${port}`,
  ];
  if (obf) lines.push(`    amnezia-wg-option:`, `      <<: *amnezia-base`, `      i1: *${obf.i1}`);
  return lines;
}

// ─────────────────────── Пул эндпоинтов ───────────────────────────────────
// origin (⭐): DNS-устойчивый хостнейм engage + 3 варианта обфускации. Это
// предпочтительные ноды; ☁️ (по IP) — резерв.
const origin = [
  comment("origin-endpoint"),
  ...endpoint("⭐", "engage.cloudflareclient.com", 500),
  ...endpoint("⭐", "engage.cloudflareclient.com", 2408),
  ...endpoint("⭐", "engage.cloudflareclient.com", 4500),
  ...endpoint("⭐", "engage.cloudflareclient.com", 4500, { label: "Alt 1", i1: "i1-alt1" }),
  ...endpoint("⭐", "162.159.192.1", 4500, { label: "Alt 2", i1: "i1-alt2" }),
  ...endpoint("⭐", "8.6.112.1", 4500, { label: "Alt 3", i1: "i1-alt3" }),
];

// relay (🎭): сторонние WARP-релеи tribukvy.ltd — выход из разных стран. Не
// участвуют в авто-выборе (фильтр ⭐|☁️), выбираются вручную через группу
// «Relay-сервера». Полезны против геоблока: выход NL/DE/FI обходит то, что
// WARP из РФ не может (напр. 403 через WARP→Cloudflare).
const RELAYS = [
  ["🇳🇱 Нидерланды", "nl.tribukvy.ltd"],
  ["🇵🇱 Польша", "pl.tribukvy.ltd"],
  ["🇷🇺 Россия", "ru0.tribukvy.ltd"],
  ["🇫🇮 Финляндия", "fi.tribukvy.ltd"],
  ["🇩🇪 Германия", "de.tribukvy.ltd"],
  ["🇱🇻 Латвия", "lv.tribukvy.ltd"],
  ["TEL 🇵🇱 Польша", "mpl.tribukvy.ltd"],
  ["TEL 🇫🇮 Финляндия", "mfi.tribukvy.ltd"],
];
const relay = [comment("relay-endpoint")];
for (const [label, server] of RELAYS) {
  relay.push(`  - name: "[🎭] ${label}"`, `    <<: *warp-common`, `    server: ${server}`, `    port: 4500`);
}

// default (☁️): каждый диапазон × каждый порт.
const cloud = [comment("default-endpoint")];
for (const ip of RANGES) for (const port of PORTS) cloud.push(...endpoint("☁️", ip, port));

// desktop: все Cloudflare (⭐ origin + ☁️ default) + сторонние релеи (🎭).
const desktopBlock = [BEGIN, ...origin, ...cloud, ...relay, END].join("\n");
// mobile: только Cloudflare WARP, без сторонних релеев.
const mobileBlock = [BEGIN, ...origin, ...cloud, END].join("\n");

const TEMPLATES = [
  { file: "clash.yaml", block: desktopBlock, relays: RELAYS.length },
  { file: "clash-mobile.yaml", block: mobileBlock, relays: 0 },
];

// ─────────────────────────────── Запись ───────────────────────────────────
const originCount = origin.filter((l) => l.includes("- name:")).length;
const cloudCount = RANGES.length * PORTS.length;

for (const { file, block, relays } of TEMPLATES) {
  const template = path.join(ROOT, "config", "templates", file);
  const lines = fs.readFileSync(template, "utf8").split("\n");
  // Маркеры ищем без учёта отступа — YAML-форматтер мог сдвинуть комментарий.
  const from = lines.findIndex((l) => l.trimStart().startsWith("# === BEGIN WARP PROXIES"));
  const to = lines.findIndex((l) => l.trimStart().startsWith(END));
  if (from < 0 || to < 0) {
    console.error(`${file}: маркеры BEGIN/END WARP PROXIES не найдены`);
    process.exit(1);
  }

  fs.writeFileSync(template, [...lines.slice(0, from), block, ...lines.slice(to + 1)].join("\n"));
  console.log(
    `✓ ${file} — ⭐ origin: ${originCount}, 🎭 relay: ${relays}, ☁️ cloud: ${cloudCount}, всего: ${originCount + relays + cloudCount}`,
  );
}
